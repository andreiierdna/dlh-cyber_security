#!/bin/bash
# =============================================================================
# Name:    7-network_deploy.sh
# Purpose: Deploy the Hawthorne perimeter: nftables from the capstone
#          segmentation contract, offline Suricata replay + custom rule
#          validation, and the local DNS filter.
# Author:  Andrei
# =============================================================================
# Output: capstone/network/{nftables.conf,firewall_validation.json,
#         suricata_alerts.json,rule_validation.json,dns_filtering.json,*logs}
# Exit: 0 every validation passed, 1 a control failed, 2 environment error.
# =============================================================================
set -o pipefail
export LC_ALL=C

ROOT=$(cd "$(dirname "$0")" && pwd)
LAB=${LAB_DIR:-/home/analyst/MedDefense_Lab}
CAP=${CAPSTONE_DIR:-$ROOT/capstone}
OUTDIR="$CAP/network"
SEG=$LAB/capstone/segmentation_rules.json
PCAPS=$LAB/capstone/PCAPs
BLOCKLIST=$LAB/capstone/dns_blocklist.txt
CUSTOM_RULES=$LAB/capstone/prior/2x04/meddefense.rules
TABLE=meddefense
# Administration reaches this host from the VirtualBox NAT segment, which is in
# no Hawthorne network. Without this exception the default-deny policy would cut
# the only remote path into the host (documented lab-only exception).
LAB_ACCESS_CIDR=${LAB_ACCESS_CIDR-10.0.2.0/24}

[ "$EUID" -eq 0 ] || { echo "Error: run as root (sudo $0)" >&2; exit 2; }
[ -r "$SEG" ] || { echo "Error: $SEG missing" >&2; exit 2; }
[ -d "$PCAPS" ] || { echo "Error: $PCAPS missing" >&2; exit 2; }
command -v nft jq >/dev/null 2>&1 || { echo "Error: nft and jq required" >&2; exit 2; }
mkdir -p "$OUTDIR"
export CAPSTONE_ARTIFACTS_DIR="$OUTDIR"
FAIL=0

# --- 1. render nftables from the Hawthorne contract -------------------------------
CONF="$OUTDIR/nftables.conf"
echo "[*] Rendering nftables from $SEG..."
{
	echo "#!/usr/sbin/nft -f"
	echo "# Hawthorne perimeter - generated by 7-network_deploy.sh from the capstone contract"
	echo "table inet $TABLE {"
	while read -r net cidr; do
		printf '\tset %s {\n\t\ttype ipv4_addr\n\t\tflags interval\n\t\telements = { %s }\n\t}\n\n' "$net" "$cidr"
	done < <(jq -r '.networks | to_entries[] | "\(.key) \(.value)"' "$SEG")
	jq -r '.default_policy.input as $p | "\tchain input {\n\t\ttype filter hook input priority filter; policy \($p);\n\n\t\tct state established,related accept\n\t\tiifname \"lo\" accept\n\t\tip protocol icmp accept\n\t\tip6 nexthdr ipv6-icmp accept\n"' "$SEG"
	jq -r '.allowed_services[] | "\(.protocol) dport \(.port) accept comment \"\(.name)\""' "$SEG" \
		| awk '{printf "\t\t%s %s %s %s %s %s\n",$1,$2,$3,$4,$5,$6}'
	[ -n "$LAB_ACCESS_CIDR" ] && printf '\t\tip saddr %s tcp dport 22 accept comment "lab-access"\n' "$LAB_ACCESS_CIDR"
	printf '\t\tlog prefix "hawthorne-drop: " limit rate 10/second\n\t\tcounter\n\t}\n\n'
	jq -r '.default_policy.forward as $p | "\tchain forward {\n\t\ttype filter hook forward priority filter; policy \($p);\n\t}"' "$SEG"
	jq -r '.default_policy.output as $p | "\tchain output {\n\t\ttype filter hook output priority filter; policy \($p);\n"' "$SEG"
	jq -r '.denied_services[] | "\t\t\(.protocol) dport \(.port) drop comment \"\(.name) denied\""' "$SEG"
	printf '\t}\n}\n'
} > "$CONF" || { echo "Error: cannot write $CONF" >&2; exit 1; }
grep -q 'chain output' "$CONF" || { echo "Error: output chain missing from render" >&2; exit 1; }

nft -c -f "$CONF" || { echo "Error: check-only parse failed" >&2; exit 1; }
BACKUP=/var/backups/nftables-hawthorne-$(date +%Y%m%d-%H%M%S).nft
nft list ruleset > "$BACKUP" 2>/dev/null || true
APPLY=$CONF
if nft list table inet "$TABLE" >/dev/null 2>&1; then
	APPLY=$(mktemp); { echo "delete table inet $TABLE"; cat "$CONF"; } > "$APPLY"
fi
nft -f "$APPLY" || { echo "Error: applying ruleset failed" >&2; exit 1; }
[ "$APPLY" != "$CONF" ] && rm -f "$APPLY"
echo "    applied (rollback: $BACKUP)"

# --- 2. firewall validation suite ---------------------------------------------------
echo "[*] Validating firewall..."
POLICY=$(nft list chain inet "$TABLE" input | sed -nE 's/.*policy ([a-z]+);.*/\1/p')
CHECKS=0; PASSED=0
fw_check() {
	local name="$1" ok="$2" detail="$3"
	CHECKS=$((CHECKS + 1))
	[ "$ok" = 1 ] && PASSED=$((PASSED + 1))
	printf '    %-40s %s\n' "$name" "$([ "$ok" = 1 ] && echo PASS || echo FAIL)"
	jq -n --arg n "$name" --arg d "$detail" --arg s "$([ "$ok" = 1 ] && echo pass || echo fail)" \
		'{check: $n, detail: $d, status: $s}' >> "$OUTDIR/firewall_checks.jsonl"
}
: > "$OUTDIR/firewall_checks.jsonl"
fw_check "input policy is drop" "$([ "$POLICY" = drop ] && echo 1 || echo 0)" "policy=$POLICY"
# Capture once: "nft list | grep -q" fails under pipefail because grep exits
# early and nft receives SIGPIPE, which looks like a missing rule.
NFT_LIST=$(nft list table inet "$TABLE")
ALLOWED_OK=1
while read -r proto port; do
	grep -qE "$proto dport $port accept" <<< "$NFT_LIST" || ALLOWED_OK=0
done < <(jq -r '.allowed_services[] | "\(.protocol) \(.port)"' "$SEG")
fw_check "every allowed service rendered" "$ALLOWED_OK" "from contract"
DENY_OK=1
while read -r proto port; do
	grep -qE "$proto dport $port drop" <<< "$NFT_LIST" || DENY_OK=0
done < <(jq -r '.denied_services[] | "\(.protocol) \(.port)"' "$SEG")
fw_check "every denied service has an explicit drop" "$DENY_OK" "from contract"
jq -s --arg ts "$(date -Iseconds)" --argjson checks "$CHECKS" --argjson passed "$PASSED" \
	' {generated_at: $ts, checks: $checks, passed: $passed,
	   failed: ($checks - $passed),
	   verdict: (if $checks == $passed then "PASS" else "FAIL" end), details: .}' \
	"$OUTDIR/firewall_checks.jsonl" > "$OUTDIR/firewall_validation.json"
[ "$CHECKS" -ne "$PASSED" ] && { echo "Error: firewall validation failed - refusing to continue" >&2; exit 1; }

# --- 3. Suricata offline replay ------------------------------------------------------
echo "[*] Preparing Suricata (offline replay only)..."
if ! command -v suricata >/dev/null 2>&1; then
	DEBIAN_FRONTEND=noninteractive apt-get install -y -qq suricata >/dev/null 2>&1 || {
		echo "Error: cannot install suricata" >&2; exit 1; }
fi
mkdir -p "$OUTDIR/logs"
YAML="$OUTDIR/suricata.yaml"
{
	printf '%%YAML 1.1\n---\nvars:\n  address-groups:\n'
	printf '    HOME_NET: "[%s]"\n    EXTERNAL_NET: "!$HOME_NET"\n' \
		"$(jq -r '.networks | to_entries | map(.value) | map(select(. != "0.0.0.0/0")) | join(",")' "$SEG"),10.10.0.0/16"
	printf '  port-groups:\n    HTTP_PORTS: "80"\n    SSH_PORTS: "22"\n\n'
	printf 'default-rule-path: %s\n' "$(dirname "$CUSTOM_RULES")"
	printf 'rule-files:\n  - %s\n\n' "$(basename "$CUSTOM_RULES")"
	printf 'default-log-dir: %s/logs\n\n' "$OUTDIR"
	printf 'outputs:\n  - eve-log:\n      enabled: yes\n      filetype: regular\n      filename: eve.json\n      types:\n        - alert\n        - dns\n        - tls\n        - files:\n'
	printf '\npcap-file: true\n'
} > "$YAML"
suricata -T -c "$YAML" > "$OUTDIR/suricata_test.log" 2>&1 || { echo "Error: suricata -T failed" >&2; tail -5 "$OUTDIR/suricata_test.log" >&2; exit 1; }

: > "$OUTDIR/alerts_combined.jsonl"
for pcap in "$PCAPS"/*.pcap; do
	[ -r "$pcap" ] || continue
	name=$(basename "$pcap" .pcap)
	rundir="$OUTDIR/replay-$name"
	rm -rf "$rundir"; mkdir -p "$rundir"
	suricata -c "$YAML" -r "$pcap" -l "$rundir" > "$OUTDIR/replay-$name.log" 2>&1
	[ -f "$rundir/eve.json" ] && jq -c 'select(.event_type=="alert")' "$rundir/eve.json" >> "$OUTDIR/alerts_combined.jsonl" 2>/dev/null
	printf '    %-28s alerts=%s\n' "$name" "$([ -f "$rundir/eve.json" ] && jq -r 'select(.event_type=="alert")' "$rundir/eve.json" 2>/dev/null | jq -s 'length' || echo 0)"
done
jq -s --arg ts "$(date -Iseconds)" '
	{generated_at: $ts, platform: "linux", mode: "offline-replay",
	 total_alerts: length,
	 by_signature: (group_by(.alert.signature) | map({key: .[0].alert.signature, value: length}) | from_entries),
	 alerts: [ .[] | {timestamp, src_ip, src_port, dest_ip, dest_port, proto,
	                   signature: .alert.signature, signature_id: .alert.signature_id,
	                   severity: .alert.severity, category: .alert.category} ]}' \
	"$OUTDIR/alerts_combined.jsonl" > "$OUTDIR/suricata_alerts.json"

# --- 4. custom rule validation against labelled PCAPs ---------------------------------
echo "[*] Validating custom rules..."
RULES_ABS=$(readlink -f "$CUSTOM_RULES")
DECLARED=$(grep -cE '^(alert|drop|pass|reject)[[:space:]]' "$RULES_ABS")
TESTS=(
	"9000001|MEDDEV to Internet|meddev_egress.pcap"
	"9000002|Guest to SMB|guest_smb.pcap"
	"9000003|Large Outbound From Server|large_outbound.pcap"
	"9000004|DNS Tunneling Long Label|dns_tunnel.pcap"
	"9000005|Clinical to Unauthorized DB|clinical_wrong_db.pcap"
	"9000006|Telnet to MEDDEV|telnet_meddev.pcap"
)
: > "$OUTDIR/rules.jsonl"
RPASS=0; RFAIL=0
for t in "${TESTS[@]}"; do
	IFS='|' read -r sid name pcap <<< "$t"
	rundir="$OUTDIR/rule-$sid"; mkdir -p "$rundir"
	if [ -r "$PCAPS/labels/$pcap" ]; then
		suricata -c "$YAML" -S "$RULES_ABS" -r "$PCAPS/labels/$pcap" -l "$rundir" > "$OUTDIR/rule-$sid.log" 2>&1
		hits=$(jq -r --argjson sid "$sid" 'select(.event_type=="alert" and .alert.signature_id==$sid)' "$rundir/eve.json" 2>/dev/null | jq -s 'length')
	else
		hits=0
	fi
	[ "${hits:-0}" -gt 0 ] && { RPASS=$((RPASS + 1)); st=PASS; } || { RFAIL=$((RFAIL + 1)); st=FAIL; }
	printf '    sid %s %-30s hits=%-4s %s\n' "$sid" "$name" "${hits:-0}" "$st"
	jq -n --arg sid "$sid" --arg name "$name" --argjson hits "${hits:-0}" --arg st "$st" \
		'{sid: $sid, name: $name, hits: $hits, status: $st}' >> "$OUTDIR/rules.jsonl"
done
jq -s --arg ts "$(date -Iseconds)" --argjson declared "$DECLARED" --argjson failed "$RFAIL" '
	{generated_at: $ts, rules_declared: $declared, validations: .,
	 summary: {rules: length, passed: ([.[] | select(.status == "PASS")] | length), failed: $failed,
	           verdict: (if $failed == 0 then "PASS" else "FAIL" end)}}' \
	"$OUTDIR/rules.jsonl" > "$OUTDIR/rule_validation.json"
[ "$RFAIL" -ne 0 ] && FAIL=1

# --- 5. DNS filtering ----------------------------------------------------------------
echo "[*] Configuring DNS filter..."
if ! dpkg-query -W dnsmasq >/dev/null 2>&1; then
	DEBIAN_FRONTEND=noninteractive apt-get install -y -qq dnsmasq >/dev/null 2>&1 || {
		echo "Error: cannot install dnsmasq" >&2; exit 1; }
fi
{
	echo '# Hawthorne DNS sinkhole - generated by 7-network_deploy.sh'
	grep -vE '^[[:space:]]*(#|$)' "$BLOCKLIST" | awk '{print "address=/" $1 "/0.0.0.0"}'
} > /etc/dnsmasq.d/meddefense-hawthorne-blocklist.conf
printf 'no-resolv\nserver=1.1.1.1\nserver=8.8.8.8\nlisten-address=127.0.0.1\nbind-interfaces\nlog-queries\nlog-facility=/var/log/dnsmasq.log\ncache-size=1000\n' \
	> /etc/dnsmasq.d/meddefense-hawthorne.conf
dnsmasq --test >/dev/null 2>&1 || { echo "Error: dnsmasq config invalid" >&2; exit 1; }
systemctl enable dnsmasq >/dev/null 2>&1
systemctl restart dnsmasq
BLOCKED=$(grep -vcE '^[[:space:]]*(#|$)' "$BLOCKLIST")
BLOCKED_DOMAIN=$(grep -vE '^[[:space:]]*(#|$)' "$BLOCKLIST" | head -1)
BLOCK_ANSWER=$(dig +short +time=3 +tries=1 @127.0.0.1 "$BLOCKED_DOMAIN" A | head -1)
ALLOW_ANSWER=$(dig +short +time=5 +tries=1 @127.0.0.1 ubuntu.com A | head -1)
DNS_OK=1
[ "$BLOCK_ANSWER" = "0.0.0.0" ] || DNS_OK=0
[ -n "$ALLOW_ANSWER" ] && [ "$ALLOW_ANSWER" != "0.0.0.0" ] || DNS_OK=0
jq -n --arg ts "$(date -Iseconds)" --arg d "$BLOCKED_DOMAIN" --arg a "$BLOCK_ANSWER" \
	--arg ad "$ALLOW_ANSWER" --argjson n "$BLOCKED" --argjson ok "$DNS_OK" '
	{generated_at: $ts, resolver: "dnsmasq on 127.0.0.1", blocked_domains: $n,
	 checks: [{domain: $d, expected: "sinkhole", answer: $a},
	          {domain: "ubuntu.com", expected: "allow", answer: $ad}],
	 status: (if $ok == 1 then "PASS" else "FAIL" end)}' > "$OUTDIR/dns_filtering.json"
[ "$DNS_OK" -eq 0 ] && FAIL=1

echo "Firewall: $PASSED/$CHECKS | Custom rules: $RPASS/$DECLARED | DNS: $([ "$DNS_OK" = 1 ] && echo PASS || echo FAIL)"
echo "Artifacts: $OUTDIR"
[ "$FAIL" -eq 0 ]

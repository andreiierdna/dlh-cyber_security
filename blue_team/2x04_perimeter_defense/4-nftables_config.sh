#!/bin/bash
# =============================================================================
# Name:    4-nftables_config.sh
# Purpose: Render segmentation_rules.json into nftables.conf, check it, apply it
#          as one atomic transaction and record the transition.
# Author:  Andrei
# =============================================================================
# MedDefense 2x04 "Perimeter Defense" - Task 4
# A wrong ruleset update locks you out of your own SSH session in one second, so:
#   1 render, 2 nft -c (check only), 3 back up the running ruleset,
#   4 apply atomically, 5 verify, 6 leave a tested rollback path.

# Usage: sudo ./4-nftables_config.sh [segmentation_rules.json]
# Idempotent: re-renders the same ruleset and replaces the table atomically.
# =============================================================================
set -o pipefail
export LC_ALL=C

SEG=${1:-segmentation_rules.json}
CONF=${2:-nftables.conf}
LAB_ACCESS_CIDR=${LAB_ACCESS_CIDR-10.0.2.0/24}
TABLE=meddefense

[ -r "$SEG" ] || { echo "Error: $SEG not found - run 2-segmentation_rules.sh first" >&2; exit 1; }
[ "$EUID" -eq 0 ] || { echo "Error: run as root (sudo $0)" >&2; exit 1; }
for c in nft jq; do command -v "$c" >/dev/null 2>&1 || { echo "Error: $c missing" >&2; exit 1; }; done

# --- 1. Render -------------------------------------------------------------------
# Set per zone, then chains. Sets carry every CIDR of the zone.
{
	echo "#!/usr/sbin/nft -f"
	echo "# MedDefense segmentation ruleset - generated by 4-nftables_config.sh"
	echo "# Source of truth: $SEG (T2). Do not edit by hand."
	echo "$(date -Iseconds)" | sed 's/^/# generated: /'
	echo
	echo "table inet $TABLE {"

	jq -r '.zones[] | "\(.name) \(.cidrs | join(", "))"' "$SEG" | while read -r name cidrs; do
		elems=$(tr ',' '\n' <<< "$cidrs" | sed 's/^ *//; s/ *$//' | paste -sd, -)
		printf '\tset %s {\n\t\ttype ipv4_addr\n\t\tflags interval\n\t\telements = { %s }\n\t}\n\n' \
			"$(tr '[:upper:]' '[:lower:]' <<< "$name")" "$elems"
	done

	cat <<'NFT'
	chain input {
		type filter hook input priority filter; policy drop;

		ct state established,related accept
		iifname "lo" accept
		ip protocol icmp accept
		ip6 nexthdr ipv6-icmp accept

		# --- flows that terminate on this host (INTERNAL server_host) ---
NFT
	# Flows that terminate on this host. INTERNAL is the local zone, so any
	# remote zone may reach the listed ports here; ALL->MGMT 53 is handled below.
	jq -r '.flows[] | select((.dst_zone == "INTERNAL" or .dst_zone == "MGMT") and .src_zone != "ALL")
		| "\(.src_zone|ascii_downcase) \(.proto) \(.dport)"' "$SEG" | \
	while read -r zone proto port; do
		printf '\t\tip saddr @%s %s dport %s accept comment "segmentation %s->local port %s"\n' \
			"$zone" "$proto" "$port" "$zone" "$port"
	done

	# ALL -> MGMT udp/tcp 53 arrives on the local resolver if it listens here
	printf '\t\t%s\n' 'udp dport 53 accept comment "ALL->MGMT dns"'
	printf '\t\t%s\n' 'tcp dport 53 accept comment "ALL->MGMT dns"'

	if [ -n "$LAB_ACCESS_CIDR" ]; then
		printf '\t\tip saddr %s tcp dport 22 accept comment "lab-access (VirtualBox NAT admin path)"\n' "$LAB_ACCESS_CIDR"
	fi

	cat <<'NFT'

		# denied packets are visible to the SOC (ufw.log / syslog)
		log prefix "meddefense-drop: " limit rate 10/second
		counter
	}

	chain forward {
		type filter hook forward priority filter; policy drop;

		ct state established,related accept
NFT
	# cross-zone allow flows (both zones remote)
	jq -r '.flows[] | select(.src_zone != "ALL")
		| "\(.src_zone|ascii_downcase) \(.dst_zone|ascii_downcase) \(.proto) \(.dport)"' "$SEG" | \
	while read -r src dst proto port; do
		printf '\t\tip saddr @%s ip daddr @%s %s dport %s accept\n' "$src" "$dst" "$proto" "$port"
	done
	cat <<'NFT'

		log prefix "meddefense-fwd-drop: " limit rate 10/second
		counter
	}

	chain output {
		type filter hook output priority filter; policy accept;

		# this host is INTERNAL: it must not initiate sessions into MEDDEV
		# (only MGMT may reach medical devices, T2 deny_all)
NFT
	printf '\t\tip daddr @meddev drop comment "INTERNAL->MEDDEV denied by design"\n'
	echo "	}"
	echo "}"
} > "$CONF" || { echo "Error: cannot write $CONF" >&2; exit 1; }

ALLOW_N=$(jq '.summary.allow_count' "$SEG")
TMPERR=$(mktemp)
trap 'rm -f "$TMPERR"' EXIT

# --- 2. Check-only parse ------------------------------------------------------------
if ! nft -c -f "$CONF" 2>"$TMPERR"; then
	echo "Error: $CONF failed the check-only parse:" >&2
	sed 's/^/  /' "$TMPERR" >&2
	exit 1
fi
echo "[*] Rendered $CONF - check-only parse OK"

# --- 3. Rollback backup --------------------------------------------------------------
BACKUP_DIR=/var/backups
STAMP=$(date +%Y%m%d-%H%M%S)
BACKUP="$BACKUP_DIR/nftables-rollback-$STAMP.nft"
mkdir -p "$BACKUP_DIR"
nft list ruleset > "$BACKUP" 2>/dev/null || true
echo "[*] Current ruleset saved: $BACKUP ($(wc -l < "$BACKUP") lines)"

# --- 4. Apply atomically ---------------------------------------------------------------
# Replacing an existing table in the same transaction keeps the switch atomic;
# a bare "table inet X" would fail with "File exists" on the second run.
APPLY="$CONF"
if nft list table inet "$TABLE" >/dev/null 2>&1; then
	APPLY=$(mktemp)
	{ echo "delete table inet $TABLE"; cat "$CONF"; } > "$APPLY"
fi
if ! nft -f "$APPLY"; then
	echo "Error: applying the ruleset failed - the previous ruleset is still in place" >&2
	exit 1
fi
[ "$APPLY" != "$CONF" ] && rm -f "$APPLY"
echo "[*] Ruleset applied atomically"

# --- 5. Verify ---------------------------------------------------------------------------
if ! nft list table inet "$TABLE" >/dev/null 2>&1; then
	echo "Error: table inet $TABLE is not present after the load" >&2
	exit 1
fi
RULES=$(nft -a list table inet "$TABLE" 2>/dev/null | grep -cE '(accept|drop|log)')
ACCEPTS=$(nft list table inet "$TABLE" 2>/dev/null | grep -c 'accept')
DROPS=$(nft list table inet "$TABLE" 2>/dev/null | grep -c 'drop')
SETS=$(nft list table inet "$TABLE" 2>/dev/null | grep -cE '^\s*set ')
POLICY_IN=$(nft list chain inet "$TABLE" input 2>/dev/null | grep -oE 'policy [a-z]+' | awk '{print $2}')
echo "    table inet $TABLE: $RULES rule statements, $SETS sets"
echo "    accepts: $ACCEPTS (plan allows $ALLOW_N)   drops: $DROPS   input policy: $POLICY_IN"

# --- 6. Rollback path ---------------------------------------------------------------------
cat > /var/backups/nftables-rollback-latest.md <<EOF
MedDefense nftables rollback
applied:   $(date -Iseconds)
table:     inet $TABLE
backup:    $BACKUP
rollback:  sudo nft delete table inet $TABLE && sudo nft -f $BACKUP
verify:    sudo nft list table inet $TABLE
EOF
echo "[*] Rollback: sudo nft delete table inet $TABLE && sudo nft -f $BACKUP"

[ "$POLICY_IN" = drop ] && [ "$ACCEPTS" -ge "$ALLOW_N" ]

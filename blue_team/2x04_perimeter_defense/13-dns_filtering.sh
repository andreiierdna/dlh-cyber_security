#!/bin/bash
# =============================================================================
# Name:    13-dns_filtering.sh
# Purpose: Local DNS sinkhole for known-malicious domains with proof that
#          blocked names answer 0.0.0.0 and legitimate names still resolve.
# Author:  Andrei
# =============================================================================
# MedDefense 2x04 "Perimeter Defense" - Task 13
# DNS is the quietest attack surface: almost never blocked, almost never
# inspected. The T9/T11 findings show a long-label TXT tunnel; a local filter
# cuts the channel at the source.
#
# Idempotent: regenerates the same config files, restarts once.
# =============================================================================
set -o pipefail
export LC_ALL=C

LAB=${LAB_DIR:-/home/analyst/MedDefense_Lab}
BLOCKLIST=${1:-$LAB/dns/blocklist.txt}
ALLOWLIST=${2:-$LAB/dns/allowlist.txt}
UPSTREAM_SRC=${3:-$LAB/dns/meddefense-upstream.conf}
OUT=${4:-dns_filtering_report.json}
BLOCK_CONF=/etc/dnsmasq.d/meddefense-blocklist.conf
UPSTREAM_CONF=/etc/dnsmasq.d/meddefense-upstream.conf
LOCAL_CONF=/etc/dnsmasq.d/meddefense-local.conf
INTERNAL_IP=${INTERNAL_IP:-10.10.1.10}

[ "$EUID" -eq 0 ] || { echo "Error: run as root (sudo $0)" >&2; exit 1; }
[ -r "$BLOCKLIST" ] || { echo "Error: $BLOCKLIST not found" >&2; exit 1; }
[ -r "$ALLOWLIST" ] || { echo "Error: $ALLOWLIST not found" >&2; exit 1; }
command -v dig >/dev/null && command -v jq >/dev/null || { echo "Error: dig and jq are required" >&2; exit 1; }

# --- 1. Package -------------------------------------------------------------------
echo "[*] Ensuring dnsmasq is installed..."
if ! dpkg-query -W -f='${Status}' dnsmasq 2>/dev/null | grep -q "install ok installed"; then
	DEBIAN_FRONTEND=noninteractive apt-get install -y -qq dnsmasq >/dev/null 2>&1 \
		|| { echo "Error: cannot install dnsmasq" >&2; exit 1; }
fi
DNSMASQ_VER=$(dnsmasq --version 2>/dev/null | head -1 | awk '{print $3}')
echo "    dnsmasq $DNSMASQ_VER"

# --- 2. Render configuration -----------------------------------------------------------
echo "[*] Rendering blocklist..."
{
	echo "# MedDefense DNS sinkhole - generated by 13-dns_filtering.sh"
	echo "# One address= line per blocked domain; subdomains are covered by dnsmasq."
	grep -vE '^[[:space:]]*(#|$)' "$BLOCKLIST" | awk '{print "address=/" $1 "/0.0.0.0"}'
} > "$BLOCK_CONF"
BLOCK_COUNT=$(grep -c '^address=' "$BLOCK_CONF")
echo "    ($BLOCK_COUNT domains)"

# Upstream forwarders (shipped file, installed verbatim)
if [ -r "$UPSTREAM_SRC" ]; then
	install -m 644 "$UPSTREAM_SRC" "$UPSTREAM_CONF"
else
	printf 'no-resolv\nserver=1.1.1.1\nserver=8.8.8.8\n' > "$UPSTREAM_CONF"
fi

# Local zone + service settings
{
	echo "# MedDefense dnsmasq service - generated by 13-dns_filtering.sh"
	echo "listen-address=127.0.0.1"
	echo "bind-interfaces"
	echo "log-queries"
	echo "log-facility=/var/log/dnsmasq.log"
	echo "cache-size=1000"
	echo "# Internal zone: allowlisted *.meddefense.local names served locally"
	grep -vE '^[[:space:]]*(#|$)' "$ALLOWLIST" | grep -i '\.meddefense\.local$' \
		| awk -v ip="$INTERNAL_IP" '{print "address=/" $1 "/" ip}'
} > "$LOCAL_CONF"

# Validate the configuration before restarting
if ! dnsmasq --test > /tmp/dnsmasq-test.log 2>&1; then
	echo "Error: dnsmasq configuration test failed" >&2
	sed 's/^/  /' /tmp/dnsmasq-test.log >&2
	exit 1
fi
echo "[*] Restarting dnsmasq.service..."
systemctl enable dnsmasq.service >/dev/null 2>&1
systemctl restart dnsmasq.service
STATE=$(systemctl is-active dnsmasq.service)
echo "    $STATE"
[ "$STATE" = active ] || { journalctl -u dnsmasq -n 5 --no-pager >&2; exit 1; }

# --- 3. Validation queries ---------------------------------------------------------------
echo "[*] Validation queries..."
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
: > "$TMP/results.jsonl"
PASS=0
FAIL=0

# query <domain> <expected: allow|sinkhole> [note]
query() {
	local domain="$1" expect="$2" answer status
	answer=$(dig +short +time=5 +tries=1 @127.0.0.1 "$domain" A 2>/dev/null | head -1)
	[ -z "$answer" ] && answer="NXDOMAIN/NONE"
	if [ "$expect" = sinkhole ]; then
		[ "$answer" = "0.0.0.0" ] && { status=pass; PASS=$((PASS + 1)); } || { status=fail; FAIL=$((FAIL + 1)); }
	else
		[ "$answer" != "0.0.0.0" ] && { status=pass; PASS=$((PASS + 1)); } || { status=fail; FAIL=$((FAIL + 1)); }
	fi
	printf '  dig @127.0.0.1 %-34s -> %-15s expected %-8s %s\n' "$domain" "$answer" "$expect" \
		"$([ "$status" = pass ] && echo PASS || echo FAIL)"
	jq -n --arg d "$domain" --arg a "$answer" --arg e "$expect" --arg s "$status" \
		'{query: $d, answer: $a, expected: $e, status: $s}' >> "$TMP/results.jsonl"
}

ALLOWED=$(grep -vE '^[[:space:]]*(#|$)' "$ALLOWLIST" | grep -v '\.meddefense\.local$' | head -1)
BLOCKED=$(grep -vE '^[[:space:]]*(#|$)' "$BLOCKLIST" | head -1)
LOCALNAME=$(grep -vE '^[[:space:]]*(#|$)' "$ALLOWLIST" | grep -i '\.meddefense\.local$' | head -1)

query "${LOCALNAME:-billing.meddefense.local}" allow
query "${BLOCKED:-c2.example}" sinkhole
query "${ALLOWED:-ubuntu.com}" allow
# A name in neither list must still reach the upstream (no wildcard sinkhole)
query "example.com" allow

jq -n --arg ts "$(date -Iseconds)" --arg host "$(hostname)" \
	--argjson blocked "$BLOCK_COUNT" --arg ver "$DNSMASQ_VER" \
	--argjson passed "$PASS" --argjson failed "$FAIL" \
	--slurpfile res "$TMP/results.jsonl" '
	{generated_at: $ts, hostname: $host, resolver: "dnsmasq \($ver) on 127.0.0.1",
	 blocked_domains: $blocked,
	 upstream_config: "/etc/dnsmasq.d/meddefense-upstream.conf",
	 blocklist_config: "/etc/dnsmasq.d/meddefense-blocklist.conf",
	 summary: {checks: ($passed + $failed), passed: $passed, failed: $failed,
	           verdict: (if $failed == 0 then "PASS" else "FAIL" end)},
	 checks: $res[0]}' > "$OUT" || { echo "Error: cannot write $OUT" >&2; exit 1; }

echo "Blocked domains: $BLOCK_COUNT | checks passed: $PASS | failed: $FAIL"
echo "Report saved to: $OUT"
[ "$FAIL" -eq 0 ]

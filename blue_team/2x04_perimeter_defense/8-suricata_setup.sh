#!/bin/bash
# =============================================================================
# Name:    8-suricata_setup.sh
# Purpose: Prepare Suricata for offline PCAP replay: rules staged, minimal
#          suricata.yaml rendered, config tested, smoke capture verified.
# Author:  Andrei
# =============================================================================
# MedDefense 2x04 "Perimeter Defense" - Task 8
# Replay mode only: the binary is pointed at a file with -r. No daemon, no
# interface, no collector. Deterministic: the same PCAP always yields the same
# alerts, which is what makes the evidence defensible.
#
# Output: suricata.yaml, setup_verification.json
# Idempotent: rules are re-copied, yaml rewritten, config re-tested.
# =============================================================================
set -o pipefail
export LC_ALL=C

LAB=${LAB_DIR:-/home/analyst/MedDefense_Lab}
SRC_RULES=$LAB/suricata/rules
DST_RULES=/var/lib/suricata/rules
YAML=${1:-suricata.yaml}
OUT=${2:-setup_verification.json}
SMOKE=$LAB/PCAPs/smoke.pcap

[ "$EUID" -eq 0 ] || { echo "Error: run as root (sudo $0)" >&2; exit 1; }
command -v jq >/dev/null 2>&1 || { echo "Error: jq is required" >&2; exit 1; }
[ -d "$SRC_RULES" ] || { echo "Error: $SRC_RULES not found" >&2; exit 1; }

# --- 1. Packages -------------------------------------------------------------------
echo "[*] Checking packages..."
for p in suricata jq; do
	if dpkg-query -W -f='${Status}' "$p" 2>/dev/null | grep -q "install ok installed"; then
		printf '    %-10s already installed\n' "$p"
	else
		DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "$p" >/dev/null 2>&1 \
			|| { echo "Error: cannot install $p" >&2; exit 1; }
		printf '    %-10s installed\n' "$p"
	fi
done
VERSION=$(suricata -V 2>/dev/null | awk '{print $(NF-1)}')

# --- 2. Stage rules -----------------------------------------------------------------
echo "[*] Staging rules into $DST_RULES..."
mkdir -p "$DST_RULES"
rm -f "$DST_RULES"/*.rules 2>/dev/null
cp -f "$SRC_RULES"/*.rules "$DST_RULES"/ 2>/dev/null
RULE_FILES=$(find "$DST_RULES" -maxdepth 1 -name '*.rules' | wc -l)
SRC_COUNT=$(find "$SRC_RULES" -maxdepth 1 -name '*.rules' | wc -l)
echo "    Rule files: $RULE_FILES/$SRC_COUNT"

# meddefense.rules is written by task 10; a placeholder keeps -T valid before that
if [ ! -f "$DST_RULES/meddefense.rules" ]; then
	cat > "$DST_RULES/meddefense.rules" <<'HDR'
# MedDefense custom rules (task 10). Placeholder until 10-rule_validation.sh runs.
HDR
fi

RULE_COUNT=$(cat "$DST_RULES"/*.rules 2>/dev/null | grep -cE '^(alert|drop|pass|reject)[[:space:]]')
echo "    Rule signatures: $RULE_COUNT"

# --- 3. Render suricata.yaml ------------------------------------------------------------
echo "[*] Rendering $YAML..."
{
	cat <<YAML
%YAML 1.1
---
# MedDefense offline-replay configuration - generated by 8-suricata_setup.sh
# Replay only: suricata -c suricata.yaml -r <pcap> -l <dir>
vars:
  address-groups:
    HOME_NET: "[10.10.0.0/16,172.16.0.0/16]"
    EXTERNAL_NET: "!\$HOME_NET"
    HTTP_SERVERS: "\$HOME_NET"
    SMTP_SERVERS: "\$HOME_NET"
    SQL_SERVERS: "\$HOME_NET"
    DNS_SERVERS: "\$HOME_NET"
  port-groups:
    HTTP_PORTS: "80"
    SHELLCODE_PORTS: "!80"
    SSH_PORTS: "22"
    DNP3_PORTS: "20000"

default-rule-path: $DST_RULES
rule-files:
YAML
	find "$DST_RULES" -maxdepth 1 -name '*.rules' -printf '%f\n' | sort | sed 's/^/  - /'
	cat <<YAML

default-log-dir: /var/log/suricata

outputs:
  - eve-log:
      enabled: yes
      filetype: regular
      filename: eve.json
      types:
        - alert:
            payload: yes
            payload-printable: yes
            packet: yes
            metadata: yes
        - http:
            extended: yes
        - dns:
            query: yes
            answer: yes
        - tls:
            extended: yes
        - files:
        - flow
  - fast:
      enabled: no

pcap-file: true

# Replay tuning: no live interfaces are inspected in this project.
threading:
  set-cpu-affinity: no
  cpu-affinity:
    - management-cpu-set:
        cpu: [ 0 ]
YAML
} > "$YAML" || { echo "Error: cannot write $YAML" >&2; exit 1; }

# --- 4. Config test -----------------------------------------------------------------------
echo "[*] Testing configuration..."
suricata -T -c "./$YAML" -v > /tmp/suricata-configtest.log 2>&1
TEST_EXIT=$?
if [ "$TEST_EXIT" -ne 0 ]; then
	echo "    suricata -T: FAILED (exit $TEST_EXIT)" >&2
	tail -5 /tmp/suricata-configtest.log | sed 's/^/      /' >&2
	exit 1
fi
echo "    suricata -T: OK (exit 0)"

# --- 5. Smoke replay -----------------------------------------------------------------------
SMOKE_DIR=/tmp/suricata-smoke
rm -rf "$SMOKE_DIR"; mkdir -p "$SMOKE_DIR"
echo "[*] Smoke replay: $(basename "$SMOKE")..."
suricata -c "./$YAML" -r "$SMOKE" -l "$SMOKE_DIR" > /tmp/suricata-smoke.log 2>&1
SMOKE_EXIT=$?
SMOKE_ALERTS=0
[ -f "$SMOKE_DIR/eve.json" ] && SMOKE_ALERTS=$(jq -r 'select(.event_type=="alert")' "$SMOKE_DIR/eve.json" 2>/dev/null | jq -s 'length')
echo "    Alerts: $SMOKE_ALERTS (suricata exit $SMOKE_EXIT)"

# --- 6. Verification artifact -----------------------------------------------------------------
jq -n --arg ts "$(date -Iseconds)" --arg host "$(hostname)" --arg ver "$VERSION" \
	--argjson files "$RULE_FILES" --argjson rules "$RULE_COUNT" \
	--argjson test "$TEST_EXIT" --argjson smoke "$SMOKE_ALERTS" --argjson sexit "$SMOKE_EXIT" \
	--arg yaml "$YAML" --arg rulesdir "$DST_RULES" --arg pcap "$SMOKE" '
	{generated_at: $ts, hostname: $host, installed_version: $ver,
	 rule_path: $rulesdir, rule_files_loaded: $files, rule_count: $rules,
	 config: $yaml, config_test_exit: $test,
	 smoke_pcap: $pcap, smoke_alerts: $smoke, smoke_exit: $sexit,
	 mode: "offline-replay",
	 verdict: (if $test == 0 and $smoke > 0 then "PASS" else "FAIL" end)}' > "$OUT" \
	|| { echo "Error: cannot write $OUT" >&2; exit 1; }

echo "Suricata $VERSION | rules $RULE_COUNT | config test $TEST_EXIT | smoke alerts $SMOKE_ALERTS"
echo "Report saved to: $OUT"
[ "$TEST_EXIT" -eq 0 ] && [ "$SMOKE_ALERTS" -gt 0 ]
